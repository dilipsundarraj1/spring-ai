package com.llm.memory.longterm;

import jakarta.annotation.PostConstruct;
import org.springframework.ai.chat.messages.AssistantMessage;
import org.springframework.ai.chat.messages.Message;
import org.springframework.ai.chat.messages.MessageType;
import org.springframework.ai.chat.messages.UserMessage;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Repository;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.SQLException;
import java.util.List;

/**
 * Append-only archive of every Turn. Never sent to the model; read to audit and to re-derive
 * Long-Term Memory when the extraction rules change.
 * <p>
 * Spring AI's JdbcChatMemoryRepository cannot be used for this: its saveAll runs
 * deleteByConversationId and re-inserts, so it replaces a conversation rather than appending to it.
 */
@Repository
public class ChatHistoryRepository {

    private static final String DDL_TEMPLATE = """
            CREATE TABLE IF NOT EXISTS chat_history (
                id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id         VARCHAR(64)  NOT NULL,
                conversation_id VARCHAR(64)  NOT NULL,
                message_type    VARCHAR(16)  NOT NULL,
                content         %s           NOT NULL,
                created_at      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL
            )
            """;

    private static final String INDEX_DDL =
            "CREATE INDEX IF NOT EXISTS chat_history_user_idx ON chat_history (user_id, id)";

    private final JdbcTemplate jdbcTemplate;

    public ChatHistoryRepository(JdbcTemplate jdbcTemplate) {
        this.jdbcTemplate = jdbcTemplate;
    }

    @PostConstruct
    void initializeSchema() {
        // same approach Spring AI's own stores take with initialize-schema, so the module needs
        // neither Flyway nor JPA
        jdbcTemplate.execute(DDL_TEMPLATE.formatted(unboundedTextType()));
        jdbcTemplate.execute(INDEX_DDL);
    }

    /**
     * Postgres spells an unbounded string TEXT; HSQLDB (used by the tests) does not know that type.
     * Spring AI solves the same problem with a dialect abstraction - one column needs only this.
     */
    private String unboundedTextType() {
        DataSource dataSource = jdbcTemplate.getDataSource();
        if (dataSource == null) {
            return "TEXT";
        }
        try (Connection connection = dataSource.getConnection()) {
            String product = connection.getMetaData().getDatabaseProductName();
            return product != null && product.toLowerCase().contains("postgre") ? "TEXT" : "LONGVARCHAR";
        }
        catch (SQLException ex) {
            throw new IllegalStateException("Could not determine the database dialect for chat_history", ex);
        }
    }

    public void append(String userId, String conversationId, List<Message> turns) {
        for (Message turn : turns) {
            jdbcTemplate.update(
                    "INSERT INTO chat_history (user_id, conversation_id, message_type, content) VALUES (?, ?, ?, ?)",
                    userId, conversationId, turn.getMessageType().name(), turn.getText());
        }
    }

    /** Every Turn the user has ever exchanged, oldest first - the raw material for a rebuild. */
    public List<Message> findAllTurns(String userId) {
        return jdbcTemplate.query(
                "SELECT message_type, content FROM chat_history WHERE user_id = ? ORDER BY id",
                (rs, rowNum) -> toMessage(rs.getString("message_type"), rs.getString("content")),
                userId);
    }

    /** Wipes the archive for one user. Needed to re-run the demo from a clean slate. */
    public int deleteByUser(String userId) {
        return jdbcTemplate.update("DELETE FROM chat_history WHERE user_id = ?", userId);
    }

    public int countTurns(String userId) {
        Integer count = jdbcTemplate.queryForObject("SELECT count(*) FROM chat_history WHERE user_id = ?",
                Integer.class, userId);
        return count == null ? 0 : count;
    }

    private static Message toMessage(String type, String content) {
        return MessageType.ASSISTANT.name().equals(type) ? new AssistantMessage(content) : new UserMessage(content);
    }
}
